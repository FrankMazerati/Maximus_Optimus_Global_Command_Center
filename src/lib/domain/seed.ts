interface CheckpointSeed {
  title: string;
  why: string;
  expected: string;
  state?: "not_started" | "in_progress" | "completed" | "unsuccessful" | "skipped";
  rule?: StarRuleId;
  actual?: string;
  skipped?: string;
  startedAt?: string;
  completedAt?: string;
}

function checkpoints(seeds: CheckpointSeed[], base: string): Mission["checkpoints"] {
  return seeds.map((seed, index) => ({
    id: `cp-${base}-${index + 1}`,
    order: index + 1,
    title: seed.title,
    why: seed.why,
    expectedResult: seed.expected,
    state: seed.state ?? "not_started",
    starRule: seed.rule ?? "checkpoint_complete",
    startedAt: seed.startedAt ?? null,
    completedAt: seed.completedAt ?? null,
    actualResult: seed.actual ?? "",
    skipReason: seed.skipped ?? "",
    evidence: [],
    updatedBy: seed.state && seed.state !== "not_started" ? ACTOR.id : null,
  }));
}

