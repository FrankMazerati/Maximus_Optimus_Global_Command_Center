/** Ledger entries derived from the checkpoints that are genuinely complete in the seed data. */
function seedLedger(): LedgerEntry[] {
  const entries: LedgerEntry[] = [];
  for (const mission of missions) {
    if (mission.acceptedBy !== "u-frank") continue;
    for (const checkpoint of mission.checkpoints) {
      if (checkpoint.state !== "completed" || !checkpoint.completedAt) continue;
      const rule = STAR_RULES[checkpoint.starRule];
      entries.push({
        id: id("led"),
        at: checkpoint.completedAt,
        kind: "star",
        ruleId: checkpoint.starRule,
        label: rule.label,
        stars: rule.stars,
        xp: rule.xp,
        sourceType: "checkpoint",
        sourceId: checkpoint.id,
        sourceLabel: `${mission.number} · ${checkpoint.title}`,
        evidence: checkpoint.actualResult,
        awardKey: awardKey(checkpoint.starRule, mission.id, checkpoint.id),
        actorId: "u-frank",
      });
    }
    if (mission.status === "completed" || mission.status === "closed") {
      entries.push({
        id: id("led"),
        at: mission.statusChangedAt,
        kind: "xp",
        ruleId: "mission_completion",
        label: "Mission completion",
        stars: 0,
        xp: MISSION_COMPLETION_XP[mission.priority] + MISSION_COMPLEXITY_XP[mission.priority],
        sourceType: "mission",
        sourceId: mission.id,
        sourceLabel: mission.number,
        evidence: "Mission completed with a verified resolution.",
        awardKey: awardKey("mission_completion", mission.id),
        actorId: mission.acceptedBy ?? "u-frank",
      });
    }
  }
  return entries;
}

